"""Assemble model_config.json payload for signal model save."""
from __future__ import annotations

from datetime import datetime

from .path_utils import to_repo_relative


def build_signal_config_dict(*, resolved, model_id, data_id, symbol,
                             features, n_params,
                             train_losses, val_losses,
                             best_epoch, diagnostics_history,
                             data_path):
    """Build the serialisable training snapshot written to model_config.json."""
    return {
        'model_id': model_id,
        'model_type': 'signal',
        'data_id': data_id,
        'symbol': symbol,
        'feature_set': resolved.get('feature_set', 'technical_bp'),
        'feature_set_requested': resolved.get('feature_set_requested',
                                              resolved.get('feature_set')),
        'feature_coverage': resolved.get('feature_coverage'),
        'feature_missing': resolved.get('feature_missing', []),
        'submodel_feature_coverage': resolved.get('submodel_feature_coverage'),
        'features': features,
        'n_features': len(features),
        'output_mode': resolved.get('output_mode', 'dual'),
        'training_profile': resolved.get('training_profile', 'baseline'),
        'lookback': resolved['lookback'],
        'horizon': resolved['horizon'],
        'hidden_size': resolved['hidden_size'],
        'num_layers': resolved['num_layers'],
        'dropout': resolved['dropout'],
        'bidirectional': resolved.get('bidirectional', False),
        'use_attention': resolved['use_attention'],
        'fc_layers': resolved['fc_layers'],
        'activation': resolved['activation'],
        'fc_norm': resolved['fc_norm'],
        'rnn_type': resolved.get('rnn_type', 'lstm'),
        'use_input_norm': resolved.get('use_input_norm', True),
        'use_feature_attention': resolved.get('use_feature_attention', False),
        'attention_heads': resolved.get('attention_heads', 1),
        'lstm_dropout': resolved.get('lstm_dropout'),
        'fc_dropout': resolved.get('fc_dropout'),
        'weight_init': resolved.get('weight_init', 'default'),
        # F6 flags
        'use_conv1d_front': resolved.get('use_conv1d_front', False),
        'conv1d_kernel': resolved.get('conv1d_kernel', 5),
        'pooling_mode': resolved.get('pooling_mode', 'last'),
        'use_fc_residual': resolved.get('use_fc_residual', False),
        'use_rnn_norm': resolved.get('use_rnn_norm', False),
        'use_learnable_output_scale': resolved.get('use_learnable_output_scale', False),
        'freeze_rnn': resolved.get('freeze_rnn', False),
        'arch_type': resolved.get('arch_type', 'legacy'),
        'submodel_size': resolved.get('submodel_size', 0),
        'use_submodel_norm': resolved.get('use_submodel_norm', True),
        'submodel_norm_type': resolved.get('submodel_norm_type', 'auto'),
        'submodel_feature_set': resolved.get('submodel_feature_set', None),
        'n_params': n_params,
        'loss_type': resolved['loss_type'],
        'loss_diversity_weight': resolved.get('loss_diversity_weight', 1.0),
        'loss_diversity_target': resolved.get('loss_diversity_target', 0.30),
        'loss_schedule_ramp_epochs': resolved.get('loss_schedule_ramp_epochs', 0),
        'signal_threshold': resolved['signal_threshold'],
        'window_sigma': resolved['window_sigma'],
        'min_signal': resolved.get('min_signal', 20.0),
        'use_signal_utility': resolved.get('use_signal_utility', False),
        'signal_utility_weight': resolved.get('signal_utility_weight', 0.05),
        'use_r2_loss': resolved.get('use_r2_loss', False),
        'r2_loss_weight': resolved.get('r2_loss_weight', 0.1),
        'use_ccc_loss': resolved.get('use_ccc_loss', False),
        'ccc_loss_weight': resolved.get('ccc_loss_weight', 0.1),
        'use_cr_ceiling': resolved.get('use_cr_ceiling', False),
        'cr_ceiling_weight': resolved.get('cr_ceiling_weight', 0.1),
        'cr_ceiling': resolved.get('cr_ceiling', 1.5),
        'use_group_dro': resolved.get('use_group_dro', False),
        'group_dro_eta': resolved.get('group_dro_eta', 0.01),
        'group_dro_groups': resolved.get('group_dro_groups', 3),
        'epochs': resolved['epochs'],
        'batch_size': resolved['batch_size'],
        'learning_rate': resolved['learning_rate'],
        'weight_decay': resolved['weight_decay'],
        'seed': resolved['seed'],
        'scheduler_type': resolved.get('scheduler_type', 'plateau'),
        'lr_warmup_epochs': resolved.get('lr_warmup_epochs', 0),
        'use_swa': resolved.get('use_swa', False),
        'swa_start_epoch': resolved.get('swa_start_epoch', 30),
        'swa_every': resolved.get('swa_every', 1),
        'early_stopping_patience': resolved.get('early_stopping_patience', 25),
        'early_stopping_min_delta': resolved.get('early_stopping_min_delta', 1e-4),
        'min_epochs_before_es': resolved.get('min_epochs_before_es', 0),
        'best_model_metric': resolved.get('best_model_metric', 'val'),
        'best_epoch': best_epoch,
        'train_losses': train_losses,
        'val_losses': val_losses,
        'diagnostics_history': diagnostics_history,
        'train_path': to_repo_relative(data_path),
        'data_source': resolved.get('data_source', 'train'),
        'data_source_auto_switched': bool(resolved.get('data_source_auto_switched', False)),
        'submodel_dirs': resolved.get('submodel_dirs', []),
        'submodel_max_missing_ratio': resolved.get('submodel_max_missing_ratio', 0.30),
        'submodel_mode': resolved.get('submodel_mode', 'real'),
        'null_submodel_size': resolved.get('null_submodel_size', 0),
        'allow_submodel_data_mismatch': bool(resolved.get('allow_submodel_data_mismatch', False)),
        'allow_partial_feature_set': bool(resolved.get('allow_partial_feature_set', False)),
        'min_feature_coverage': resolved.get('min_feature_coverage', 1.0),
        'timestamp': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
    }
